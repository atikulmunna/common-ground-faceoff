-- Every table that belongs to a conversation now has a foreign key to it with ON DELETE CASCADE,
-- so deleting a conversation removes everything that belongs to it, and an analysis round can be
-- saved only once per conversation.
--
-- Before adding the constraints, remove rows that would violate them (decided 2026-11-12):

-- 1. Rows pointing at conversations that no longer exist. These tables had no foreign key, so a
--    deleted conversation could leave them behind; nothing could reach them any more.
DELETE FROM "FeedbackRating" WHERE "sessionId" NOT IN (SELECT "id" FROM "Session");
DELETE FROM "SectionReaction" WHERE "sessionId" NOT IN (SELECT "id" FROM "Session");
DELETE FROM "SectionComment" WHERE "sessionId" NOT IN (SELECT "id" FROM "Session");
DELETE FROM "RedactionLog" WHERE "sessionId" NOT IN (SELECT "id" FROM "Session");
DELETE FROM "ModerationFlag" WHERE "sessionId" NOT IN (SELECT "id" FROM "Session");
DELETE FROM "NotificationEmail" WHERE "sessionId" IS NOT NULL AND "sessionId" NOT IN (SELECT "id" FROM "Session");

-- 2. Rounds saved more than once (possible before analysis claiming): keep the newest result.
DELETE FROM "AnalysisResult" AS older
USING "AnalysisResult" AS newer
WHERE older."sessionId" = newer."sessionId"
  AND older."roundNumber" = newer."roundNumber"
  AND (older."createdAt" < newer."createdAt" OR (older."createdAt" = newer."createdAt" AND older."id" < newer."id"));

